import { contributionGrid, scaleTo } from "../lib/series";
import type { ScoreBreakdown, Startup, WarmthFactor } from "./types";

type StartupInput = Omit<Startup, "signal" | "warmth" | "scores"> & {
  scores: Omit<ScoreBreakdown, "warmth">;
};

/** Signal and warmth are derived, never hand-typed, so every surface agrees. */
function defineStartup(input: StartupInput): Startup {
  const warmth = input.warmthFactors.reduce((sum, f) => sum + f.points, 0);
  const scores = { ...input.scores, warmth };
  const signal = Math.round((scores.trust + scores.traction + scores.velocity + scores.warmth) / 4);
  return { ...input, scores, warmth, signal };
}

